import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const outputDir = new URL('../dist/', import.meta.url);
const output = new URL('client.js', outputDir);
const { outputFiles: [artifact], metafile } = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/plugin.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'react-dom'],
  metafile: true,
  write: false,
});

const packageDirs = new Set();
for (const input of Object.keys(metafile.inputs)) {
  const match = input.match(/^node_modules\/(?:.*\/node_modules\/)?(?:@[^/]+\/)?[^/]+\//);
  if (match) packageDirs.add(match[0].slice(0, -1));
}
const licenses = new Map();
for (const dir of [...packageDirs].sort()) {
  const packagePath = path.join(root, dir);
  const entries = await readdir(packagePath);
  const licenseFile = entries.sort().find(name => /^license(?:\.|$)/i.test(name));
  if (!licenseFile) throw new Error(`Missing license for bundled dependency ${dir}`);
  const license = (await readFile(path.join(packagePath, licenseFile), 'utf8')).trim().replace(/\r\n/g, '\n');
  if (!licenses.has(license)) licenses.set(license, []);
  licenses.get(license).push(dir.split('node_modules/').at(-1));
}
const notices = [...licenses].map(([license, names]) => {
  return ['// Bundled dependencies: ' + names.join(', '), ...license.split('\n').map(line => line ? `// ${line}` : '//')].join('\n');
}).join('\n\n');

// DSH loads one lazy browser factory and provides React through require().
const bundle = `// Generated by npm run build:client. Edit src/client/ instead.
${notices}

window.__ModuleLoader__.load({
  id: 'dsh-plantuml',
  factory(require) {
    const module = { exports: {} };
${artifact.text.trimEnd().split('\n').map(line => line ? `    ${line}` : '').join('\n')}
    return module.exports;
  },
});
`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== bundle) {
    console.error('client.js is out of date. Run npm run build:client.');
    process.exitCode = 1;
  }
} else {
  await mkdir(outputDir, { recursive: true });
  await writeFile(output, bundle);
}
