import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const outputDir = new URL('../dist/', import.meta.url);
const output = new URL('client.js', outputDir);
const { outputFiles: [artifact] } = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/plugin.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  write: false,
});

// DSH loads one lazy browser factory and provides React through require().
const bundle = `// Generated by npm run build:client. Edit src/client/ instead.
window.__ModuleLoader__.load({
  id: 'dsh-plantuml',
  factory(require) {
    const module = { exports: {} };
${artifact.text.trimEnd().split('\n').map(line => line ? `    ${line}` : '').join('\n')}
    return module.exports;
  },
});
`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== bundle) {
    console.error('client.js is out of date. Run npm run build:client.');
    process.exitCode = 1;
  }
} else {
  await mkdir(outputDir, { recursive: true });
  await writeFile(output, bundle);
}
